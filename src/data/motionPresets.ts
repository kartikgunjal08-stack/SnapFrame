const VARIANT_NAMES = ["Studio", "Kinetic", "Prism", "Direct"];

export const MOTION_PRESETS: MotionPreset[] = ARCHETYPES.flatMap((arch, aIdx) =>
  VARIANT_NAMES.map((variantLabel, vIdx): MotionPreset => {
    const palette = PALETTES[(aIdx * 3 + vIdx * 2) % PALETTES.length];
    const isMobileCategory = arch.category === "Mobile Phone & Reels";
    const frameStyle = isMobileCategory
      ? "iphone"
      : arch.category === "App Store & Kinetic Frames" && arch.slug === "appstore-float"
        ? "iphone"
        : FRAMES[(aIdx + vIdx) % FRAMES.length];
    const duration: MotionDuration =
      vIdx === 0 ? arch.duration : vIdx === 1 ? 3 : vIdx === 2 ? 5 : 8;

    return {
      id: `motion-${arch.slug}-${vIdx + 1}`,
      name: vIdx === 0 ? arch.name : `${arch.name} · ${variantLabel}`,
      category: arch.category,
      description: arch.description,
      defaultDuration: duration,
      defaultEasing: vIdx === 2 ? "spring" : vIdx === 3 ? "easeInOut" : arch.easing,
      defaultAspect: isMobileCategory ? "9:16" : undefined,
      frameStyle,
      backdropColors: palette.colors,
      pattern: palette.pattern,
      eyebrowDefault: arch.eyebrow,
      headlineDefault: arch.headline,
      motion: {
        ...arch.motion,
        tiltY: vIdx % 2 === 0 ? arch.motion.tiltY : -arch.motion.tiltY,
        shimmerSweep: vIdx % 2 === 0 ? arch.motion.shimmerSweep : !arch.motion.shimmerSweep,
      },
    };
  })
);

